#!/usr/bin/env python3
"""Build the beat map of a replicated script from its move notes (statur-story-replication, step 2 check).

Usage: python3 -I build_beatmap.py <seed.yaml> <03-script.md> > 02-beatmap.md

The script marks each move with a note line before its text:
    > B07.6 TERM+DEFINE+EXAMPLE x3 · F164 F163
This tool lists, block by block, every seed move next to the target move (first 22 words of the text that follows
the note, cues shown as [CUE]) and its fact ids, and flags seed moves with no note (MISSING) and notes with no seed
move (EXTRA). It needs no YAML library: it reads the seed's `moves:` lists line by line.
"""
import re, sys

seed_path, script_path = sys.argv[1], sys.argv[2]
blocks, cur = {}, None
for line in open(seed_path, encoding='utf-8'):
    m = re.match(r'\s*- id: (B\d\d)', line)
    if m:
        cur = m.group(1); blocks[cur] = {'moves': [], 'meta': {}}; continue
    if cur is None:
        continue
    m = re.match(r'\s+(beat|share|words|purpose): (.*)', line)
    if m and m.group(1) not in blocks[cur]['meta']:
        blocks[cur]['meta'][m.group(1)] = m.group(2).strip().strip('"')
    m = re.match(r'\s+- \[([^,]+), "(.*?)", "(.*?)"\]', line)
    if m:
        blocks[cur]['moves'].append((m.group(1).strip(), m.group(2), m.group(3)))

notes, order, cur_note, buf = {}, [], None, []
def flush():
    if cur_note:
        text = ' '.join(buf)
        text = re.sub(r'\[(CARD|CLIP|MEME|B-ROLL|RETELLING|TITLE CARD|CUT TO BLACK)[^\]]*\]', '[CUE]', text)
        text = re.sub(r'\s*\[(?:F\d+(?:,\s*F\d+)*|HYPO)\]', '', text)
        notes[cur_note[0]]['text'] = ' '.join(text.split()[:22])
for raw in open(script_path, encoding='utf-8'):
    line = raw.strip()
    m = re.match(r'^>\s*(B\d\d)\.(\d+)\s+(.*)$', line)
    if m:
        flush(); buf = []
        key = (m.group(1), int(m.group(2)))
        rest = m.group(3).split('·')
        notes[key] = {'codes': rest[0].strip(), 'facts': rest[1].strip() if len(rest) > 1 else '', 'text': ''}
        cur_note = (key,); order.append(key); continue
    if line.startswith('#') or line.startswith('>'):
        if line.startswith('## '):
            flush(); cur_note = None; buf = []
        continue
    if cur_note and line:
        buf.append(line)
flush()

print('# Beat map · generated\n')
print('Source move (from the seed) on the left, target move (first words of the script text) on the right, fact ids last. Generated by scripts/build_beatmap.py from the move notes of 03-script.md.\n')
missing = extra = 0
for b, d in blocks.items():
    meta = d['meta']
    print(f"\n## {b} · {meta.get('beat','')} · seed words {meta.get('words','')}\n")
    print(f"Purpose: {meta.get('purpose','')}\n")
    print('| # | codes | source move | target move | facts |\n|---|---|---|---|---|')
    for i, (codes, move, ex) in enumerate(d['moves'], 1):
        n = notes.get((b, i))
        if n is None:
            missing += 1
            print(f"| {i} | {codes} | {move} (source: {ex}) | MISSING | |")
        else:
            print(f"| {i} | {codes} | {move} (source: {ex}) | {n['text']} | {n['facts']} |")
    for (nb, ni), n in notes.items():
        if nb == b and ni > len(d['moves']):
            extra += 1
            print(f"| {ni} | {n['codes']} | EXTRA | {n['text']} | {n['facts']} |")
print(f"\nMoves: {sum(len(d['moves']) for d in blocks.values())} in the seed, {len(notes)} notes in the script, {missing} missing, {extra} extra.")
